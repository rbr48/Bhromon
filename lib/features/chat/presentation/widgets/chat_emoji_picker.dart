  @override
  void initState() {
    super.initState();
    _pageController = PageController(initialPage: _selectedCategoryIndex);
  }

  @override
  void dispose() {
    _pageController.dispose();
    super.dispose();
  }

  void _onCategoryTapped(int index) {
    setState(() => _selectedCategoryIndex = index);
    _pageController.jumpToPage(index);
  }

  @override
  Widget build(BuildContext context) {
    return Container(
      height: widget.height,
      color: context.chat.bar, // WhatsApp dark slate background
      child: Column(
        children: [
          // Category selector tab bar
          Container(
            height: 44,
            color: context.chat.recessedDeep,
            padding: const EdgeInsets.symmetric(horizontal: 4),
            child: Row(
              children: [
                Expanded(
                  child: ListView.builder(
                    scrollDirection: Axis.horizontal,
                    itemCount: _categories.length,
                    itemBuilder: (context, idx) {
                      final isSelected = idx == _selectedCategoryIndex;
                      return InkWell(
                        onTap: () => _onCategoryTapped(idx),
                        borderRadius: BorderRadius.circular(8),
                        child: Container(
                          padding: const EdgeInsets.symmetric(horizontal: 14),
                          alignment: Alignment.center,
                          decoration: BoxDecoration(
                            border: Border(
                              bottom: BorderSide(
                                color: isSelected
                                    ? AppColors.chatGreen
                                    : Colors.transparent,
                                width: 3,
                              ),
                            ),
                          ),
                          child: Icon(
                            _categories[idx].icon,
                            color: isSelected
                                ? context.chat.accentText
                                : context.chat.grey,
                            size: 20,
                          ),
                        ),
                      );
                    },
                  ),
                ),
                // Backspace button on the right of category header
                IconButton(
                  tooltip: context.l10n.translate('chat_action_delete'),
                  icon: Icon(
                    Icons.backspace_outlined,
                    color: context.chat.grey,
                    size: 20,
                  ),
                  onPressed: widget.onBackspace,
                ),
              ],
            ),
          ),
          // Emoji grid per category
          Expanded(
            child: PageView.builder(
              controller: _pageController,
              onPageChanged: (idx) {
                setState(() => _selectedCategoryIndex = idx);
              },
              itemCount: _categories.length,
              itemBuilder: (context, catIdx) {
                final category = _categories[catIdx];
                return GridView.builder(
                  padding:
                      const EdgeInsets.symmetric(horizontal: 8, vertical: 8),
                  physics: const BouncingScrollPhysics(),
                  gridDelegate: const SliverGridDelegateWithFixedCrossAxisCount(
                    crossAxisCount: 8,
                    mainAxisSpacing: 4,
                    crossAxisSpacing: 4,
                  ),
                  itemCount: category.emojis.length,
                  itemBuilder: (context, emojiIdx) {
                    final emoji = category.emojis[emojiIdx];
                    return InkWell(
                      borderRadius: BorderRadius.circular(8),
                      onTap: () => widget.onEmojiSelected(emoji),
                      child: Center(
                        child: Text(
                          emoji,
                          style: const TextStyle(fontSize: 24),
                        ),
                      ),
                    );
                  },
                );
              },
            ),
          ),
        ],
      ),
    );
  }
